def tapered_plug_diameters(entry_diameter, bottom_diameter, socket_depth,
                           plug_length, interference, socket_compensation=None,
                           plug_compensation=None):
    """Return CAD base/tip diameters without conflating acoustic-hole compensation."""
    socket_compensation = (FDM_DRY_SEAL_SOCKET_COMPENSATION
                           if socket_compensation is None else socket_compensation)
    plug_compensation = (FDM_DRY_SEAL_PLUG_COMPENSATION
                         if plug_compensation is None else plug_compensation)
    slope = (entry_diameter - bottom_diameter) / socket_depth
    socket_at_tip = entry_diameter - slope * plug_length
    base = entry_diameter + interference + plug_compensation - socket_compensation
    tip = socket_at_tip + interference + plug_compensation - socket_compensation
    stock = DRY_SEAL_SURFACE_EXTRA_STOCK
    return base + stock, tip + stock


